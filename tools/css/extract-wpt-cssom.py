MUTATES = re.compile(r'insertRule|deleteRule|removeRule|appendRule|addRule|selectorText\s*=|keyText\s*=|mediaText\s*=|appendMedium|deleteMedium|replaceSync|\.replace\(|\.name\s*=|\.disabled\s*=|adoptedStyleSheets')


def poison(state, text):
    """A statement or test the reader did not recognize ran in the page: what it did to the page's elements and sheets is missing from the world the later tests run in."""
    state['poisoned'] = True
    if MUTATES.search(text):
        state['sheets_poisoned'] = True


def read_expr(node, env, ops):
    """('value', S, name) etc.: the read an assertion compares: returns (op name, args)."""
    if node[0] == 'member' and node[2] in ('mediaText', 'length'):
        m = media_target(node[1], env)
        if m is not None:
            return ('assert_mtext' if node[2] == 'mediaText' else 'assert_mlen', [m])
    if node[0] == 'call' and node[1][0] == 'member' and node[1][2] == 'item' and len(node[2]) == 1 and node[2][0][0] == 'num':
        m = media_target(node[1][1], env)
        if m is not None:
            return ('assert_mitem', [m, str(int(node[2][0][1]))])
    if node[0] == 'member' and node[2] in RULE_ATTRS_READ:
        c = try_chain(node[1], env)
        if c and c[0] == 'rule':
            return ('assert_rattr', [c[1], node[2]])
    if node[0] == 'member' and node[1] == ('var', 'document') and node[2] == 'styleSheets':
        raise Unrecognized(R_RULES)
    if node[0] == 'member' and node[2] == 'length' and node[1] == ('member', ('var', 'document'), 'styleSheets'):
        if not env.page.sheets_ok:
            raise Unrecognized(R_STYLEATTR if env.page.styles else R_RULES)
        return ('assert_nsheets', [])
    if node[0] == 'member' and node[2] in ('length', 'type', 'parentRule', 'parentStyleSheet'):
        c = try_chain(node[1], env) if node[2] in ('length', 'type') else try_chain(node, env)
        if node[2] == 'length' and c and c[0] == 'list':
            return ('assert_rlen', [c[1]])
        if node[2] == 'type' and c and c[0] == 'rule':
            return ('assert_rtype', [c[1]])
        if node[2] in ('parentRule', 'parentStyleSheet') and c:
            return ('assert_rsame', [c[1]])
    if node[0] == 'call' and node[1][0] == 'member':
        obj, meth = node[1][1], node[1][2]
        if obj == ('var', 'CSS') and meth == 'escape' and len(node[2]) == 1:
            a = node[2][0]
            if a[0] == 'bool':
                text = 'true' if a[1] else 'false'
            elif a[0] == 'null':
                text = 'null'
            elif a[0] == 'undefined':
                text = 'undefined'
            else:
                text = js_string(a, 'text')
            return ('assert_escape', [text])
        if meth in ('getPropertyValue', 'getPropertyPriority', 'removeProperty') and len(node[2]) == 1:
            s = style_expr(obj, env, ops)
            return ({'getPropertyValue': 'assert_value', 'getPropertyPriority': 'assert_priority', 'removeProperty': 'assert_remove'}[meth], [s, js_string(node[2][0], 'name')])
        if meth == 'item' and len(node[2]) == 1 and node[2][0][0] == 'num':
            s = style_expr(obj, env, ops)
            return ('assert_item', [s, str(int(node[2][0][1]))])
        if meth == 'getAttribute' and len(node[2]) == 1 and node[2][0] == ('str', 'style'):
            return ('assert_getattr', [elem_expr(obj, env, ops)])
        raise Unrecognized(classify_node(node))
    if node[0] == 'member':
        obj, name = node[1], node[2]
        if name == 'cssText':
            c = try_chain(obj, env)
            if c and c[0] == 'rule':
                return ('assert_rcsstext', [c[1]])
            return ('assert_csstext', [style_expr(obj, env, ops)])
        if name == 'length':
            return ('assert_length', [style_expr(obj, env, ops)])
        if name in ('cssFloat',) or name == 'parentRule':
            if name == 'parentRule':
                raise Unrecognized(R_RULES)
        if name in ('getPropertyValue', 'setProperty', 'item', 'removeProperty', 'getPropertyPriority', 'parentRule'):
            raise Unrecognized(R_SHAPE)
        s = style_expr(obj, env, ops)
        return ('assert_attr', [s, name])
    if node[0] == 'index':
        s = style_expr(node[1], env, ops)
        if node[2][0] == 'num':
            return ('assert_item', [s, str(int(node[2][1]))])
        return ('assert_attr', [s, js_string(node[2], 'attribute')])
    raise Unrecognized(R_SHAPE)


def classify_node(node):
    return R_SHAPE


def literal(node):
    if node[0] == 'member' and node[1] == ('var', 'CSSRule') and node[2] in CSSRULE_CONSTANTS:
        return str(CSSRULE_CONSTANTS[node[2]])
    if node[0] == 'undefined':
        return '\x01undefined'
    if node[0] == 'null':
        return '\x01null'
    if node[0] in ('str', 'add'):
        return js_string(node, 'expected')
    if node[0] == 'num':
        return js_string(node, 'expected')
    raise Unrecognized(R_SHAPE)



def rule_call(e, env, ops, expect, result=None):
    """`X.insertRule(text[, index])`, `X.deleteRule(index)`, `X.removeRule(index)`, `X.appendRule(text)`, `X.deleteRule(selector)` of a keyframes rule: the op that makes the call and
    the exception it must throw (`ok` for none). The result an assertion names is the index insertRule returns."""
    callee, args = e[1], e[2]
    if callee[0] != 'member':
        raise Unrecognized(R_SHAPE)
    if callee[2] in ('appendMedium', 'deleteMedium') and len(args) == 1:
        m = media_target(callee[1], env)
        if m is not None:
            ops.append(('mappend' if callee[2] == 'appendMedium' else 'mdelete', m, js_string(args[0], 'medium'), expect))
            return
    c = try_chain(callee[1], env)
    if not c or c[0] not in ('sheet', 'rule'):
        raise Unrecognized(R_RULES)
    meth = callee[2]
    if meth == 'insertRule' and len(args) in (1, 2):
        text = js_string(args[0], 'rule')
        if len(args) == 2:
            if args[1][0] == 'undefined':
                index = '\x01undefined'
            elif args[1][0] == 'num' and args[1][1] == int(args[1][1]) and args[1][1] >= 0:
                index = str(int(args[1][1]))
            else:
                raise Unrecognized(R_SHAPE)
        else:
            index = '\x01undefined'
        ops.append(('rinsert', c[1], index, text, expect, result if result is not None else '\x01undefined'))
        return
    if meth == 'addRule' and len(args) in (1, 2, 3) and c[0] == 'sheet':
        sel = js_string(args[0], 'selector')
        style = js_string(args[1], 'style') if len(args) >= 2 else 'undefined'
        index = str(int(args[2][1])) if len(args) == 3 and args[2][0] == 'num' else '\x01undefined'
        if len(args) == 3 and args[2][0] != 'num':
            raise Unrecognized(R_SHAPE)
        ops.append(('radd', c[1], sel, style, index, expect, result if result is not None else '\x01undefined'))
        return
    if meth in ('deleteRule', 'removeRule') and len(args) == 1:
        if args[0][0] == 'num' and args[0][1] == int(args[0][1]) and args[0][1] >= 0:
            ops.append(('rdelete', c[1], str(int(args[0][1])), expect))
            return
        if args[0][0] == 'str' and meth == 'deleteRule' and c[0] == 'rule':
            ops.append(('rkfdelete', c[1], args[0][1], expect))
            return
        if meth == 'removeRule' and len(args) == 0:
            ops.append(('rdelete', c[1], '0', expect))
            return
    if meth == 'removeRule' and len(args) == 0 and c[0] == 'sheet':
        ops.append(('rdelete', c[1], '0', expect))
        return
    if meth == 'appendRule' and len(args) == 1 and c[0] == 'rule':
        ops.append(('rappend', c[1], js_string(args[0], 'rule'), expect))
        return
    raise Unrecognized(R_SHAPE)


def statement_ops(st, env, ops):
    kind = st[0]
    if kind == 'decl':
        name, e = st[1], st[2]
        c = try_chain(e, env)
        if c:
            # the variable holds the object, not the path to it: a later insertion or deletion does not change what it names
            env.counter[0] += 1
            slot = '$v%d' % env.counter[0]
            ops.append(('bind', slot, c[1]))
            env.vars[name] = ('chain', c[0], slot)
            return
        if e[0] == 'member' and e[2] == 'style':
            env.vars[name] = ('style', style_expr(e, env, ops))
            return
        if e[0] == 'call' or e[0] == 'var':
            env.vars[name] = ('elem', elem_expr(e, env, ops))
            return
        raise Unrecognized(R_SHAPE)
    if kind == 'destructure':
        names, e = st[1], st[2]
        if names == ['style']:
            env.vars['style'] = ('style', style_expr(('member', e, 'style'), env, ops))
            return
        raise Unrecognized(R_SHAPE)
    if kind == 'assign':
        target, value = st[1], st[2]
        if target[0] == 'member':
            obj, name = target[1], target[2]
            if name == 'mediaText':
                m = media_target(obj, env)
                if m is not None:
                    ops.append(('mset', m, js_string(value, 'text'), 'ok'))
                    return
            rc = try_chain(obj, env)
            if rc and rc[0] == 'rule' and name not in ('length', 'parentRule', 'type', 'cssRules'):
                ops.append(('rset', rc[1], name, js_string(value, 'value'), 'ok'))
                return
            if name == 'cssText':
                ops.append(('csstext', style_expr(obj, env, ops), js_string(value, 'text')))
                return
            if name in ('length', 'parentRule', 'getPropertyValue', 'setProperty', 'item', 'removeProperty'):
                raise Unrecognized(R_SHAPE)
            ops.append(('attr', style_expr(obj, env, ops), name, js_string(value, 'value')))
            return
        if target[0] == 'index' and target[1][0] != 'num':
            ops.append(('attr', style_expr(target[1], env, ops), js_string(target[2], 'attribute'), js_string(value, 'value')))
            return
        raise Unrecognized(R_SHAPE)
    e = st[1]
    if e[0] != 'call':
        raise Unrecognized(R_SHAPE)
    callee, args = e[1], e[2]
    if callee[0] == 'var' and callee[1] == 'assert_throws_dom' and len(args) == 2 and args[0][0] == 'str' and args[1][0] == 'func':
        params, body = body_statements(args[1])
        if len(body) != 1 or body[0][0] != 'expr' or body[0][1][0] != 'call':
            raise Unrecognized(R_SHAPE)
        sub = []
        rule_call(body[0][1], env, sub, expect=args[0][1])
        ops.extend(sub)
        return
    if callee[0] == 'var':
        fn = callee[1]
        if fn == 'assert_any' and len(args) == 3 and args[0] == ('var', 'assert_equals') and args[2][0] == 'array':
            op, a = read_expr(args[1], env, ops)
            ops.append(('anyof_' + op,) + tuple(a) + ('\x1f'.join(js_string(x, 'expected') for x in args[2][1]),))
            return
        if fn in ('assert_equals', 'assert_not_equals'):
            if len(args) not in (2, 3):
                raise Unrecognized(R_SHAPE)
            if fn == 'assert_not_equals':
                raise Unrecognized(R_SHAPE)
            if args[0][0] == 'call' and args[0][1][0] == 'member' and args[0][1][2] in ('insertRule', 'addRule') and args[1][0] == 'num':
                rule_call(args[0], env, ops, expect='ok', result=str(int(args[1][1])))
                return
            if args[1][0] in ('member', 'index', 'var') and not (args[1][0] == 'var' and args[1][1] not in env.vars):
                first, second = try_chain(args[0], env), try_chain(args[1], env)
                if first and second and first[0] == second[0] and first[0] in ('rule', 'sheet'):
                    ops.append(('assert_rsame', first[1], second[1]))
                    return
            op, a = read_expr(args[0], env, ops)
            exp = literal(args[1])
            ops.append((op,) + tuple(a) + (exp,))
            return
        raise Unrecognized(R_SHAPE)
    if callee[0] == 'member' and callee[2] in ('insertRule', 'deleteRule', 'removeRule', 'addRule', 'appendRule') and try_chain(callee[1], env):
        rule_call(e, env, ops, expect='ok')
        return
    if callee[0] == 'member' and callee[2] in ('appendMedium', 'deleteMedium') and media_target(callee[1], env) is not None:
        rule_call(e, env, ops, expect='ok')
        return
    if callee[0] == 'member':
        obj, meth = callee[1], callee[2]
        if meth == 'setProperty' and len(args) in (2, 3):
            ops.append(('set', style_expr(obj, env, ops), js_string(args[0], 'name'), js_string(args[1], 'value'), js_string(args[2], 'priority') if len(args) == 3 else ''))
            return
        if meth == 'removeProperty' and len(args) == 1:
            ops.append(('remove', style_expr(obj, env, ops), js_string(args[0], 'name')))
            return
        if meth == 'setAttribute' and len(args) == 2 and args[0] == ('str', 'style'):
            ops.append(('setattr', elem_expr(obj, env, ops), js_string(args[1], 'text')))
            return
        if meth == 'removeAttribute' and len(args) == 1 and args[0] == ('str', 'style'):
            ops.append(('rmattr', elem_expr(obj, env, ops)))
            return
        if meth == 'add_cleanup' and len(args) == 1 and args[0][0] == 'func':
            # the function runs after the test, whether or not it passed: its ops are the end of the test's
            params, body = body_statements(args[0])
            cenv = env.copy()
            cops = []
            for b in body:
                statement_ops(b, cenv, cops)
            env.cleanups.extend(cops)
            return
        if meth == 'appendChild' and len(args) == 1 and args[0][0] == 'var' and args[0][1] in env.vars and env.vars[args[0][1]][0] == 'elem':
            return   # whether an element is in the document changes nothing a declaration reads
    raise Unrecognized(R_SHAPE)


def body_statements(func):
    params, body = func[1], func[2]
    if len(body) == 1 and isinstance(body[0], tuple):
        return params, [('expr', body[0])]
    return params, [parse_statement(s) for s in split_statements(body)]


def mentions_known(toks, env):
    names = set(env.vars) | {'document'}
    return any(t.kind == 'ident' and t.text in names for t in toks)


def extract_script(page, script, rel, prog, state, unextracted):
    """The page program of one script: the ops of its top-level statements and of its tests, in order, on one world."""
    try:
        toks = tokenize(script)
    except Unrecognized as u:
        unextracted.append((rel, 1, u.reason))
        poison(state, text)
        return
    env = state['env']
    for toks_ in split_statements(toks):
        text = ' '.join(t.text for t in toks_)
        first = toks_[0]
        if first.kind == 'str' and len(toks_) == 1:
            continue   # a directive ("use strict")
        if first.kind == 'ident' and first.text in ('setup', 'add_completion_callback') and len(toks_) > 1 and toks_[1].text == '(':
            continue   # the harness's own configuration
        try:
            st = parse_statement(toks_)
        except Unrecognized as u:
            if re.search(r'\btest\s*\(|async_test|promise_test', text):
                unextracted.append((rel, max(1, len(re.findall(r'\btest\s*\(|async_test|promise_test', text))),
                                    R_GENERATED if first.text in ('for', 'while', 'function', 'var', 'let', 'const') or u.reason == R_LOOP else classify(text)))
            elif first.kind == 'ident' and first.text == 'function':
                # a helper function: a test that calls it is unrecognized, unless it is `function f() { return EXPR; }`, which is read as that expression
                try:
                    if len(toks_) > 6 and toks_[1].kind == 'ident' and toks_[2].text == '(' and toks_[3].text == ')' and toks_[4].text == '{' and toks_[5].text == 'return' \
                            and toks_[-1].text == '}':
                        env.functions[toks_[1].text] = parse_expr(toks_[6:-1] if toks_[-2].text != ';' else toks_[6:-2])
                except Unrecognized:
                    pass
            else:
                unextracted.append((rel, 1, classify(text) if classify(text) != R_SHAPE else u.reason))
                poison(state, text)
            continue
        if st[0] == 'expr' and st[1][0] == 'call' and st[1][1] == ('var', 'test'):
            args = st[1][2]
            idx = state['tests']
            state['tests'] += 1
            if not args or args[0][0] != 'func':
                unextracted.append((rel, 1, R_SHAPE))
                poison(state, text)
                continue
            tenv = env.copy()
            ops = []
            try:
                params, body = body_statements(args[0])
                for b in body:
                    statement_ops(b, tenv, ops)
                if not any(o[0].startswith('assert_') or o[0].startswith('anyof_') for o in ops):
                    raise Unrecognized(R_SHAPE)
                if tenv.cleanups:
                    ops.append(('cleanup',))
                    ops.extend(tenv.cleanups)
                if (state['poisoned'] and any(n in env.globals for n in tenv.touched)) or (state['sheets_poisoned'] and any(o[0] in SHEET_STATE_OPS for o in ops)):
                    raise Unrecognized(R_SHARED)
            except Unrecognized as u:
                text_body = ' '.join(t.text for t in args[0][2]) if args[0][2] and isinstance(args[0][2][0], Tok) else ''
                unextracted.append((rel, 1, u.reason if u.reason != R_SHAPE else classify(text_body)))
                poison(state, text)
                continue
            prog.append(('test', str(idx)))
            prog.extend(ops)
            continue
        if re.search(r'\btest\s*\(', text):
            unextracted.append((rel, 1, R_GENERATED))
            poison(state, text)
            continue
        # a declaration, or a statement that acts on the world: its ops are part of the program, in order
        before = len(prog)
        marked = state['tests'] > 0
        if marked:
            prog.append(('toplevel',))   # the page's own statement between two tests: it is not part of the test before it
        try:
            statement_ops(st, env, prog)
            if marked and len(prog) == before + 1:
                del prog[before]
            if st[0] in ('decl', 'destructure', 'assign', 'expr'):
                for o in prog[before:]:
                    if o[0] == 'elem':
                        env.globals.add(o[1])
                for t in toks_:
                    pass
            if st[0] == 'decl' and env.vars.get(st[1], ('',))[0] == 'elem':
                env.globals.add(env.vars[st[1]][1])
        except Unrecognized as u:
            del prog[before:]
            if st[0] == 'expr' and st[1][0] == 'call' and st[1][1][0] == 'var' and st[1][1][1] in ('setup', 'add_completion_callback', 'done'):
                continue
            if st[0] == 'decl' and not mentions_known(toks_, env):
                continue   # a variable the tests cannot use: a test that names it is unrecognized
            unextracted.append((rel, 1, classify(text) if classify(text) != R_SHAPE else u.reason))
            poison(state, text)


HELPERS = re.compile(r'testcommon|/css/support/|computed-testcommon|serialize-testcommon|parsing-testcommon|interpolation-testcommon|inheritance-testcommon|numeric-testcommon')


def scan_page(wpt, rel, programs, unextracted):
    path = os.path.join(wpt, rel)
    try:
        text = open(path, encoding='utf-8', errors='surrogateescape').read()
    except OSError:
        return False
    if not TOUCH.search(text):
        return False
    is_js = rel.endswith('.js')
    harness = 'testharness.js' in text or rel.endswith(('.window.js', '.any.js', '.worker.js'))
    if re.search(r'rel=["\']?(match|mismatch)', text):
        unextracted.append((rel, 1, R_REFTEST))
        return True
    if not harness:
        unextracted.append((rel, 1, R_NOHARNESS))
        return True
    if is_js:
        if rel.endswith('.worker.js'):
            unextracted.append((rel, 1, R_LAYOUT))
            return True
        page = Page(rel, text, True)
        scripts = [text]
    else:
        col = Collector()
        try:
            col.feed(text)
        except Exception:
            unextracted.append((rel, 1, R_SHAPE))
            return True
        page = Page(rel, text, False)
        page.elements = col.elements
        page.styles = col.styles
        page.sheets_ok = bool(col.styles) and all(not st[1] for st in col.styles)
        page.quirks = not re.match(r'\s*(<!--.*?-->\s*)*<!doctype\s+html', text, re.I | re.S) and not rel.endswith(('.xht', '.xhtml', '.svg'))
        if any(HELPERS.search(s) for s in col.helper_scripts):
            n = len(re.findall(r'\btest_\w+\s*\(|\bruntTests?\s*\(|\bruntest\s*\(', text))
            unextracted.append((rel, max(1, n), helper_reason(col.helper_scripts)))
            return True
        if not col.scripts:
            unextracted.append((rel, 1, R_NOCALLS))
            return True
        scripts = col.scripts
    # the program starts with the elements the markup has
    prog = [('elem', idname(i), tag, style if style is not None else '') for i, (tag, style) in sorted(page.elements.items())]
    if page.sheets_ok and re.search(r'styleSheets|\.sheet\b', text):
        prog += [('sheet', str(n), st[2]) for n, st in enumerate(page.styles)]
    state = {'env': Env(page), 'poisoned': False, 'sheets_poisoned': False, 'tests': 0}
    state['env'].globals = {idname(i) for i in page.elements}
    for sc in scripts:
        extract_script(page, sc, rel, prog, state, unextracted)
    if state['tests'] == 0 and not any(r == rel for r, _, _ in unextracted):
        unextracted.append((rel, 1, R_NOCALLS))
    ntests = sum(1 for o in prog if o[0] == 'test')
    if ntests == 0 and EVAL is not None and not is_js and rel.endswith(('.html', '.htm')):
        interpret_page(wpt, rel, text, unextracted)
    if ntests:
        programs.append({'file': rel, 'quirks': page.quirks, 'ops': [list(o) for o in prog], 'tests': ntests})
    return True


def interpret_page(wpt, rel, text, unextracted):
    """Offer a page to the evaluator. It is read when the evaluator ran every statement of the page's top level (so that the set of its tests is known); then its lines in
    ``unextracted`` are the evaluator's, one for each test it could not turn into ops, and the others are in the script program."""
    import importlib.util
    census = _census()
    calls, marks, helpers = census.features(wpt, rel, False)
    blocked = {'timing', 'input-driver', 'frame-or-popup', 'typed-om', 'register-property', 'view-transition', 'custom-element', 'fonts'}
    if blocked & set(marks) or helpers:
        return
    res = EVAL.evaluate_page(rel, text)
    if res is None or not res.tests:
        return
    unextracted[:] = [u for u in unextracted if u[0] != rel]
    for t in res.tests:
        if t.reason is not None:
            unextracted.append((rel, 1, EVAL.reason_code(t.reason)))
    SCRIPT_PAGES.append((rel, res))


_CENSUS = None


def _census():
    global _CENSUS
    if _CENSUS is None:
        import importlib.util
        spec = importlib.util.spec_from_file_location('census_wpt_script_pages', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'census-wpt-script-pages.py'))
        _CENSUS = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(_CENSUS)
    return _CENSUS


SKIP_DIRS = {'support', 'resources', 'reference', 'tools', 'META.yml', 'work-in-progress'}


def walk(wpt):
    root = os.path.join(wpt, 'css')
    out = []
    for d, dirs, files in os.walk(root):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
        for f in sorted(files):
            if not f.endswith(('.html', '.htm', '.xht', '.xhtml', '.svg', '.js')):
                continue
            if re.search(r'-ref\d*\.|-notref\.|\.ref\.', f) or f.startswith('META') or f.endswith('-manual.html') or '-manual.' in f:
                continue
            if f.endswith('.js') and not f.endswith(('.window.js', '.any.js', '.worker.js')):
                continue
            out.append(os.path.relpath(os.path.join(d, f), wpt))
    return out


def rule_vector_programs(path, programs):
    """The rule vectors of the pinned pages (``test_valid_rule`` and kin of css/support/parsing-testcommon.js, read by extract-wpt-props.py into ``rule.json``), as programs: each
    page's vectors are one program, ``<page>?rule-vectors``. As the helper runs them, a vector is a fresh empty sheet: a valid rule is inserted with ``insertRule(rule)`` (one rule
    results), its ``cssText`` is the canonical serialization the page names, the rule is deleted, the serialization is inserted again and must read back the same; an invalid rule
    is a SyntaxError and leaves the sheet empty."""
    vectors = json.load(open(path, encoding='utf-8'))
    by_file = {}
    for v in vectors:
        by_file.setdefault(v['file'], []).append(v)
    for file, vs in sorted(by_file.items()):
        ops = []
        for i, v in enumerate(vs):
            # the keyframes name vectors set the text of a <style> (the helper's _set_style): the sheet is parsed from `@keyframes <name> {}`
            ops.append(('sheet', str(i), '@keyframes %s {}' % v['value'] if v['sub'].startswith('keyframes') else ''))
        for i, v in enumerate(vs):
            sp = 'S%d' % i
            ops.append(('test', str(i)))
            if v['sub'].startswith('keyframes'):
                ops.append(('assert_rlen', sp, '1' if v['sub'] == 'keyframes-valid' else '0'))
            elif v['sub'] == 'valid':
                expected = v.get('expected', v['value'])
                ops.append(('rinsert', sp, '\x01undefined', v['value'], 'ok', '\x01undefined'))
                ops.append(('assert_rlen', sp, '1'))
                ops.append(('assert_rcsstext', sp + '.R0', expected))
                ops.append(('rdelete', sp, '0', 'ok'))
                ops.append(('assert_rlen', sp, '0'))
                ops.append(('rinsert', sp, '\x01undefined', expected, 'ok', '\x01undefined'))
                ops.append(('assert_rlen', sp, '1'))
                ops.append(('assert_rcsstext', sp + '.R0', expected))
            else:
                ops.append(('rinsert', sp, '\x01undefined', v['value'], 'SyntaxError', '\x01undefined'))
                ops.append(('assert_rlen', sp, '0'))
        programs.append({'file': file + '?rule-vectors', 'quirks': False, 'ops': [list(o) for o in ops], 'tests': len(vs)})


def main():
    wpt, out = sys.argv[1], sys.argv[2]
    rules = sys.argv[3] if len(sys.argv) > 3 else None
    os.makedirs(out, exist_ok=True)
    global EVAL
    if '--no-interpreter' not in sys.argv:
        EVAL = _load_evaluator()
    programs = []
    unextracted = []
    pages = 0
    for rel in walk(wpt):
        if scan_page(wpt, rel, programs, unextracted):
            pages += 1
    if rules:
        rule_vector_programs(rules, programs)
    # The partition: one line for a page and a reason, with the number of tests.
    counts = {}
    for rel, n, reason in unextracted:
        counts[(rel, reason)] = counts.get((rel, reason), 0) + n
    with open(os.path.join(out, 'UNEXTRACTED_CSSOM'), 'w', encoding='utf-8', newline='\n') as f:
        for (rel, reason), n in sorted(counts.items()):
            f.write('%s\t%d\t%s\n' % (rel, n, reason))
    # The programs: `P file quirks tests`, then one line for each op, the fields separated by tabs with \\, \t and \n escaped, as WTF-8 (a lone surrogate of a script's string stays).
    with open(os.path.join(out, 'declaration.tsv'), 'wb') as f:
        for v in programs:
            f.write(('P\t%s\t%d\t%d\n' % (esc(v['file']), 1 if v['quirks'] else 0, v['tests'])).encode('utf-8', 'surrogatepass'))
            for o in v['ops']:
                f.write(('O\t' + '\t'.join(esc(str(x)) for x in o) + '\n').encode('utf-8', 'surrogatepass'))
    tests = sum(v['tests'] for v in programs)
    with open(os.path.join(out, 'script.tsv'), 'wb') as f, open(os.path.join(out, 'script-tests.tsv'), 'wb') as meta:
        meta.write(b'# page, test index, name (the title the evaluator gives it; empty when the page computes it), model or the reason code\n')
        for rel, res in sorted(SCRIPT_PAGES, key=lambda x: x[0]):
            if any(t.reason is None for t in res.tests):
                f.write(EVAL.render_program(rel, res))
            for t in res.tests:
                meta.write(('%s\t%d\t%s\t%s\n' % (rel, t.index, esc(t.name), 'model' if t.reason is None else EVAL.reason_code(t.reason))).encode('utf-8', 'surrogatepass'))
    script_tests = sum(len(res.tests) for _, res in SCRIPT_PAGES)
    print('extract-wpt-cssom: %d pages touch the CSSOM IDL; %d tests of %d pages are read; %d unread (page, reason) pairs; the interpreter reads %d pages (%d tests)' % (
        pages, tests, len(programs), len(counts), len(SCRIPT_PAGES), script_tests))


if __name__ == '__main__':
    main()
