# ---- tokens ---------------------------------------------------------------------------------------------------------------------------------

ESC = {'n': '\n', 't': '\t', 'r': '\r', 'b': '\b', 'f': '\f', 'v': '\v', '0': '\0'}


def unescape_js(body):
    out = []
    i = 0
    while i < len(body):
        c = body[i]
        if c != '\\':
            out.append(c)
            i += 1
            continue
        i += 1
        if i >= len(body):
            break
        c = body[i]
        if c in ESC and not (c == '0' and i + 1 < len(body) and body[i + 1].isdigit()):
            out.append(ESC[c])
            i += 1
        elif c == 'x' and re.match(r'[0-9a-fA-F]{2}', body[i + 1:i + 3]):
            out.append(chr(int(body[i + 1:i + 3], 16)))
            i += 3
        elif c == 'u' and body[i + 1:i + 2] == '{':
            j = body.find('}', i)
            out.append(chr(int(body[i + 2:j], 16)))
            i = j + 1
        elif c == 'u' and re.match(r'[0-9a-fA-F]{4}', body[i + 1:i + 5]):
            cp = int(body[i + 1:i + 5], 16)
            if 0xD800 <= cp <= 0xDBFF and body[i + 5:i + 7] == '\\u' and re.match(r'[dD][c-fC-F][0-9a-fA-F]{2}', body[i + 7:i + 11]):
                lo = int(body[i + 7:i + 11], 16)
                out.append(chr(0x10000 + ((cp - 0xD800) << 10) + (lo - 0xDC00)))
                i += 11
            else:
                out.append(chr(cp))
                i += 5
        elif c == '\n':
            i += 1
        elif c == '\r':
            i += 2 if body[i + 1:i + 2] == '\n' else 1
        else:
            out.append(c)
            i += 1
    return ''.join(out)


class Tok:
    __slots__ = ('kind', 'text', 'value', 'nl')

    def __init__(self, kind, text, value=None, nl=False):
        self.kind = kind    # ident, num, str, tmpl, punct, regex
        self.text = text
        self.value = value
        self.nl = nl        # a line break precedes it

    def __repr__(self):
        return '%s:%s' % (self.kind, self.text)


PUNCT = ['>>>=', '...', '===', '!==', '**=', '<<=', '>>=', '>>>', '&&=', '||=', '??=', '=>', '==', '!=', '<=', '>=', '&&', '||', '??', '++', '--', '+=', '-=', '*=', '/=',
         '%=', '&=', '|=', '^=', '**', '<<', '>>', '?.']


def tokenize(src):
    toks = []
    i = 0
    n = len(src)
    nl = False
    while i < n:
        c = src[i]
        if c in ' \t\r\f\v\u00a0\ufeff':
            i += 1
            continue
        if c == '\n':
            nl = True
            i += 1
            continue
        if src.startswith('//', i):
            j = src.find('\n', i)
            i = n if j < 0 else j
            continue
        if src.startswith('/*', i):
            j = src.find('*/', i + 2)
            if '\n' in src[i:(n if j < 0 else j)]:
                nl = True
            i = n if j < 0 else j + 2
            continue
        if c in '"\'':
            j = i + 1
            while j < n and src[j] != c:
                j += 2 if src[j] == '\\' else 1
            if j >= n:
                raise Unrecognized(R_SHAPE)
            toks.append(Tok('str', src[i:j + 1], unescape_js(src[i + 1:j]), nl))
            i = j + 1
        elif c == '`':
            j = i + 1
            sub = False
            while j < n and src[j] != '`':
                if src[j] == '\\':
                    j += 2
                    continue
                if src.startswith('${', j):
                    sub = True
                    depth = 1
                    j += 2
                    while j < n and depth:
                        depth += {'{': 1, '}': -1}.get(src[j], 0)
                        j += 1
                    continue
                j += 1
            toks.append(Tok('tmpl', src[i:j + 1], None if sub else unescape_js(src[i + 1:j]), nl))
            i = j + 1
        elif c.isdigit() or (c == '.' and i + 1 < n and src[i + 1].isdigit()):
            m = re.compile(r'0[xX][0-9a-fA-F]+|\d+\.?\d*(?:[eE][+-]?\d+)?|\.\d+(?:[eE][+-]?\d+)?').match(src, i)
            toks.append(Tok('num', m.group(0), float(int(m.group(0), 16)) if m.group(0)[:2] in ('0x', '0X') else float(m.group(0)), nl))
            i = m.end()
        elif c.isalpha() or c in '_$':
            m = re.compile(r'[A-Za-z_$][\w$]*').match(src, i)
            toks.append(Tok('ident', m.group(0), None, nl))
            i = m.end()
        elif c == '/' and (not toks or (toks[-1].kind == 'punct' and toks[-1].text not in (')', ']', '}')) or (toks[-1].kind == 'ident' and toks[-1].text in ('return', 'typeof'))):
            j = i + 1
            incls = False
            while j < n and (src[j] != '/' or incls):
                if src[j] == '\\':
                    j += 1
                elif src[j] == '[':
                    incls = True
                elif src[j] == ']':
                    incls = False
                elif src[j] == '\n':
                    raise Unrecognized(R_SHAPE)
                j += 1
            j += 1
            while j < n and src[j].isalpha():
                j += 1
            toks.append(Tok('regex', src[i:j], None, nl))
            i = j
        else:
            for p in PUNCT:
                if src.startswith(p, i):
                    toks.append(Tok('punct', p, None, nl))
                    i += len(p)
                    break
            else:
                toks.append(Tok('punct', c, None, nl))
                i += 1
        nl = False
    return toks


# ---- statements -----------------------------------------------------------------------------------------------------------------------------

OPEN = {'(': ')', '[': ']', '{': '}'}
BLOCK_KW = {'function', 'if', 'for', 'while', 'do', 'switch', 'try', 'class', 'async'}


def split_statements(toks):
    """The statements of a token list: ended by `;` at depth 0, by the `}` that closes a block statement, or by a line break that cannot continue the expression."""
    out = []
    cur = []
    depth = 0
    i = 0
    while i < len(toks):
        t = toks[i]
        if t.kind == 'punct' and t.text in OPEN:
            depth += 1
        elif t.kind == 'punct' and t.text in (')', ']', '}'):
            depth -= 1
        if depth == 0 and t.kind == 'punct' and t.text == ';':
            if cur:
                out.append(cur)
            cur = []
            i += 1
            continue
        cur.append(t)
        i += 1
        if depth == 0 and t.kind == 'punct' and t.text == '}' and cur and cur[0].kind == 'ident' and cur[0].text in BLOCK_KW:
            nxt = toks[i] if i < len(toks) else None
            if not (nxt and nxt.kind == 'ident' and nxt.text in ('else', 'catch', 'finally', 'while')):
                out.append(cur)
                cur = []
                continue
        if depth == 0 and i < len(toks) and toks[i].nl and t.kind in ('punct', 'ident', 'num', 'str', 'tmpl', 'regex'):
            nxt = toks[i]
            ends = t.kind != 'punct' or t.text in (')', ']', '}', '++', '--')
            continues = nxt.kind == 'punct' and nxt.text not in ('{', '[', '(', '!', '+', '-', '~') or (nxt.kind == 'ident' and nxt.text in ('instanceof', 'in', 'of'))
            if ends and not continues and not (nxt.kind == 'punct' and nxt.text in ('(', '[')):
                out.append(cur)
                cur = []
    if cur:
        out.append(cur)
    return out


# ---- expressions ---------------------------------------------------------------------------------------------------------------------------

class P:
    """A recursive descent reader of the expressions the recognized forms use. Anything else raises Unrecognized with the reason its first token gives."""

    def __init__(self, toks):
        self.t = toks
        self.i = 0

    def peek(self, k=0):
        return self.t[self.i + k] if self.i + k < len(self.t) else None

    def eat(self, text=None, kind=None):
        tok = self.peek()
        if tok is None or (text is not None and tok.text != text) or (kind is not None and tok.kind != kind):
            raise Unrecognized(R_SHAPE)
        self.i += 1
        return tok

    def at(self, text):
        tok = self.peek()
        return tok is not None and tok.kind == 'punct' and tok.text == text

    def expr(self):
        left = self.unary()
        while True:
            tok = self.peek()
            if tok and tok.kind == 'punct' and tok.text == '+':
                self.i += 1
                right = self.unary()
                left = ('add', left, right)
            elif tok and tok.kind == 'punct' and tok.text in ('===', '==', '!==', '!=', '&&', '||', '-', '*', '/', '<', '>', '<=', '>=', '?', '??'):
                raise Unrecognized(R_SHAPE)
            else:
                return left

    def unary(self):
        tok = self.peek()
        if tok is None:
            raise Unrecognized(R_SHAPE)
        if tok.kind == 'punct' and tok.text in ('!', '-', '+', '~', '++', '--'):
            if tok.text == '-' and self.peek(1) and self.peek(1).kind == 'num':
                self.i += 2
                return self.postfix(('num', -self.t[self.i - 1].value))
            raise Unrecognized(R_SHAPE)
        if tok.kind == 'ident' and tok.text in ('typeof', 'delete', 'void', 'await', 'yield', 'new'):
            if tok.text == 'new':
                self.i += 1
                callee = self.eat(kind='ident').text
                if callee in ('Promise', 'MutationObserver', 'Event'):
                    raise Unrecognized(R_EVENTS)
                raise Unrecognized(R_SHAPE)
            if tok.text == 'await':
                raise Unrecognized(R_EVENTS)
            raise Unrecognized(R_SHAPE)
        return self.postfix(self.primary())

    def primary(self):
        tok = self.eat()
        if tok.kind == 'str':
            return ('str', tok.value)
        if tok.kind == 'tmpl':
            if tok.value is None:
                raise Unrecognized(R_SHAPE)
            return ('str', tok.value)
        if tok.kind == 'num':
            return ('num', tok.value)
        if tok.kind == 'regex':
            raise Unrecognized(R_SHAPE)
        if tok.kind == 'ident':
            if tok.text == 'null':
                return ('null',)
            if tok.text in ('true', 'false'):
                return ('bool', tok.text == 'true')
            if tok.text == 'undefined':
                return ('undefined',)
            if tok.text in ('function', 'async', 'class', 'this'):
                raise Unrecognized(R_SHAPE)
            if self.at('=>'):
                self.i += 1
                return self.arrow([tok.text])
            return ('var', tok.text)
        if tok.kind == 'punct' and tok.text == '(':
            # an arrow function's parameters, or a parenthesized expression
            save = self.i
            params = []
            try:
                while not self.at(')'):
                    params.append(self.eat(kind='ident').text)
                    if self.at(','):
                        self.i += 1
                self.eat(')')
                if self.at('=>'):
                    self.i += 1
                    return self.arrow(params)
            except Unrecognized:
                pass
            self.i = save
            e = self.expr()
            self.eat(')')
            return e
        if tok.kind == 'punct' and tok.text == '[':
            items = []
            while not self.at(']'):
                items.append(self.expr())
                if self.at(','):
                    self.i += 1
            self.eat(']')
            return ('array', items)
        if tok.kind == 'punct' and tok.text == '{':
            raise Unrecognized(R_SHAPE)
        raise Unrecognized(R_SHAPE)

    def arrow(self, params):
        if self.at('{'):
            start = self.i
            depth = 0
            while True:
                tok = self.eat()
                if tok.kind == 'punct' and tok.text == '{':
                    depth += 1
                elif tok.kind == 'punct' and tok.text == '}':
                    depth -= 1
                    if depth == 0:
                        break
            return ('func', params, self.t[start + 1:self.i - 1])
        e = self.expr()
        return ('func', params, [e])

    def postfix(self, node):
        while True:
            tok = self.peek()
            if tok is None:
                return node
            if tok.kind == 'punct' and tok.text == '.':
                self.i += 1
                name = self.eat(kind='ident').text
                node = ('member', node, name)
            elif tok.kind == 'punct' and tok.text == '[':
                self.i += 1
                idx = self.expr()
                self.eat(']')
                node = ('index', node, idx)
            elif tok.kind == 'punct' and tok.text == '(':
                self.i += 1
                args = []
                while not self.at(')'):
                    if self.at('function') or (self.peek().kind == 'ident' and self.peek().text == 'function'):
                        args.append(self.function_expr())
                    else:
                        args.append(self.expr())
                    if self.at(','):
                        self.i += 1
                    elif not self.at(')'):
                        raise Unrecognized(R_SHAPE)
                self.eat(')')
                node = ('call', node, args)
            else:
                return node

    def function_expr(self):
        self.eat('function')
        if self.peek().kind == 'ident':
            self.i += 1
        self.eat('(')
        params = []
        while not self.at(')'):
            params.append(self.eat(kind='ident').text)
            if self.at(','):
                self.i += 1
        self.eat(')')
        start = self.i
        depth = 0
        while True:
            tok = self.eat()
            if tok.kind == 'punct' and tok.text == '{':
                depth += 1
            elif tok.kind == 'punct' and tok.text == '}':
                depth -= 1
                if depth == 0:
                    break
        return ('func', params, self.t[start + 1:self.i - 1])

    def args_function_first(self):
        return None


def parse_expr(toks):
    p = P(toks)
    # a function expression as an argument is handled in postfix(); a bare one at the start is not an expression the reader needs
    node = p.expr()
    if p.peek() is not None:
        raise Unrecognized(R_SHAPE)
    return node


def parse_statement(toks):
    """('decl', name, expr) | ('assign', target-expr, expr) | ('expr', expr) | ('destructure', [names], expr)."""
    if not toks:
        raise Unrecognized(R_SHAPE)
    first = toks[0]
    if first.kind == 'ident' and first.text in ('var', 'let', 'const'):
        if len(toks) > 1 and toks[1].kind == 'punct' and toks[1].text == '{':
            end = next(i for i, t in enumerate(toks) if t.kind == 'punct' and t.text == '}')
            names = [t.text for t in toks[2:end] if t.kind == 'ident']
            if not (end + 1 < len(toks) and toks[end + 1].text == '='):
                raise Unrecognized(R_SHAPE)
            return ('destructure', names, parse_expr(toks[end + 2:]))
        if len(toks) < 4 or toks[1].kind != 'ident' or toks[2].text != '=':
            raise Unrecognized(R_SHAPE)
        return ('decl', toks[1].text, parse_expr(toks[3:]))
    if first.kind == 'ident' and first.text in ('for', 'while', 'do'):
        raise Unrecognized(R_LOOP)
    if first.kind == 'ident' and first.text in ('if', 'switch', 'try', 'function', 'class', 'return', 'throw', 'async', 'await'):
        raise Unrecognized(R_SHAPE)
    # an assignment: the first `=` at depth 0
    depth = 0
    for k, t in enumerate(toks):
        if t.kind == 'punct' and t.text in OPEN:
            depth += 1
        elif t.kind == 'punct' and t.text in (')', ']', '}'):
            depth -= 1
        elif depth == 0 and t.kind == 'punct' and t.text == '=':
            return ('assign', parse_expr(toks[:k]), parse_expr(toks[k + 1:]))
        elif depth == 0 and t.kind == 'punct' and t.text in ('+=', '-=', '*=', '/=', '||=', '&&=', '??='):
            raise Unrecognized(R_SHAPE)
    return ('expr', parse_expr(toks))


def classify(text):
    if os.environ.get('CSSOM_DEBUG'):
        print('CLASSIFY', text[:200].replace('\n', ' '), file=sys.stderr)
    """The reason a construct the reader does not recognize gives, by what the statement mentions."""
    if re.search(r'getComputedStyle|computedStyleMap', text):
        return R_COMPUTED
    if re.search(r'cssRules|insertRule|deleteRule|styleSheets|CSSStyleSheet|\.sheet\b|adoptedStyleSheets|replaceSync|replace\(|CSSRule|CSSImportRule|CSSKeyframes|CSSMediaRule|CSSStyleRule|\.rules\b|addRule|removeRule|appendRule|findRule|selectorText|keyText|conditionText|MediaList|mediaText|appendMedium|deleteMedium|\.media\b', text):
        return R_RULES
    if re.search(r'CSS\.supports|matchMedia|CSS\.registerProperty|CSS\.px|CSS\.number|attributeStyleMap|computedStyleMap', text):
        return R_CSSNS
    if re.search(r'async_test|promise_test|Promise|await|MutationObserver|requestAnimationFrame|setTimeout|addEventListener|dispatchEvent|\.then\(|onload', text):
        return R_EVENTS
    if re.search(r'\bfor\b|\bwhile\b|forEach|\.map\(|Object\.keys|\bof\b', text):
        return R_LOOP
    if re.search(r'getBoundingClientRect|offsetWidth|offsetHeight|offsetLeft|offsetTop|clientWidth|scrollTop|querySelector|matches\(|appendChild|innerHTML|insertBefore|getAnimations|animate\(|document\.body|document\.documentElement|shadowRoot|attachShadow|getClientRects|offsetParent', text):
        return R_LAYOUT
    return R_SHAPE


