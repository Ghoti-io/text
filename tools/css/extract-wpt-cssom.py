def helper_reason(sources):
    """``helper:<names>``: the base names (without ``.js``) of the scripts a page loads besides the harness, sorted and joined by ``+``."""
    names = sorted({re.sub(r'\.js$', '', os.path.basename(s.split('?')[0].split('#')[0])) for s in sources if os.path.basename(s.split('?')[0].split('#')[0]) not in HARNESS_SCRIPTS})
