"""Fail when the generated seeds of a CSS fuzz corpus are not what their generator writes.

    tools/css/check-fuzz-seed-generators.py [--control]

Each tools/css/make-fuzz-NAME-seeds.py writes the committed seeds of tests/fuzz/corpus/CORPUS: the files named `*.seed` that are not `reproducer-*.seed` (a reproducer is
a recorded input of a fixed defect; the fuzzer's own finds are named by their hash and are not seeds). When a generator's input changes (the pin's list of shorthands moves the
number of every shorthand after it, a harness gains an option byte) and the corpus is not written again, the committed seeds are no longer the ones the generator describes: the
next person to run it rewrites a few hundred files that nobody reviewed, and what the corpus reaches is not what the generator's comments say. This runs every generator into an
empty scratch directory and compares it with the corpus: the same names, the same bytes. A name only in the corpus is a seed nothing makes any more (stale); a name only in the
generator is a seed that was never committed; a name in both with other bytes is a seed that moved.

--control shows the check can fail: it changes one generated byte, and removes one generated file, and requires the report each time.

Copyright 2026 by Corey Pennycuff
"""
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CORPUS = os.path.join(ROOT, "tests", "fuzz", "corpus")

# generator name -> (corpus directory, the argument that carries the output directory: its index in argv)
GENERATORS = [
    ("compute", "css-compute", 1),
    ("container", "css-container", 1),
    ("custom", "css-custom", 1),
    ("condition", "css-condition", 1),
    ("transition", "css-transition", 1),
    ("atrule", "css-atrule", 1),
    ("selector", "css-selector", 1),
    ("sheet", "css-sheet", 1),
    ("style", "css-style", 1),
    ("cssom", "cssom-decl", 1),
    ("match", "css-match", 1),
    ("sheet-cssom", "cssom-sheet", 1),
    ("document-cssom", "cssom-document", 1),
]


def seeds(directory):
    return {f for f in os.listdir(directory) if f.endswith(".seed") and not f.startswith("reproducer-")}


def generate(name, scratch):
    script = os.path.join(HERE, "make-fuzz-%s-seeds.py" % name)
    done = subprocess.run([sys.executable, "-I", script, scratch], capture_output=True, text=True)
    if done.returncode != 0:
        return None, done.stderr.strip() or done.stdout.strip()
    return done, ""


def compare(name, corpus, scratch):
    """The problems of one generator: a list of strings."""
    made, committed = seeds(scratch), seeds(os.path.join(CORPUS, corpus))
    problems = []
    for f in sorted(committed - made):
        problems.append("%s: %s is in %s and nothing makes it any more" % (name, f, corpus))
    for f in sorted(made - committed):
        problems.append("%s: %s is made and not in %s" % (name, f, corpus))
    for f in sorted(made & committed):
        with open(os.path.join(scratch, f), "rb") as a, open(os.path.join(CORPUS, corpus, f), "rb") as b:
            if a.read() != b.read():
                problems.append("%s: %s is not the bytes the generator writes" % (name, f))
    return problems


def check(only=None):
    problems = []
    count = 0
    for name, corpus, _ in GENERATORS:
        if only and name not in only:
            continue
        scratch = tempfile.mkdtemp(prefix="seed-gen-")
        try:
            done, why = generate(name, scratch)
            if done is None:
                problems.append("%s: the generator failed: %s" % (name, why))
                continue
            problems += compare(name, corpus, scratch)
            count += len(seeds(scratch))
        finally:
            shutil.rmtree(scratch, ignore_errors=True)
    return problems, count


def control():
    """The check has to see a seed that moved and a seed that is missing."""
    name, corpus, _ = GENERATORS[0]
    scratch = tempfile.mkdtemp(prefix="seed-gen-")
    try:
        done, why = generate(name, scratch)
        if done is None:
            print("control: the generator failed: %s" % why)
            return 1
        names = sorted(seeds(scratch))
        first = os.path.join(scratch, names[0])
        data = open(first, "rb").read()
        open(first, "wb").write(data + b"x")
        if not any("not the bytes" in p for p in compare(name, corpus, scratch)):
            print("control: a seed with another byte was not reported")
            return 1
        open(first, "wb").write(data)
        os.remove(os.path.join(scratch, names[1]))
        if not any("is in %s and nothing makes it" % corpus in p for p in compare(name, corpus, scratch)):
            print("control: a seed the generator no longer writes was not reported")
            return 1
        extra = os.path.join(scratch, "planted-extra.seed")
        open(extra, "wb").write(b"x")
        open(os.path.join(scratch, names[1]), "wb").write(open(os.path.join(CORPUS, corpus, names[1]), "rb").read())
        if not any("is made and not in" in p for p in compare(name, corpus, scratch)):
            print("control: a seed that was never committed was not reported")
            return 1
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    print("control: a moved seed, a stale seed and a missing seed are each reported")
    return 0


def main(argv):
    if "--control" in argv:
        return control()
    only = [a for a in argv[1:] if not a.startswith("-")]
    problems, count = check(only)
    for p in problems:
        print(p)
    if problems:
        print("fuzz seed generators: %d problems; run the generator named, which writes the corpus, and commit what it changed" % len(problems))
        return 1
    print("fuzz seed generators: %d seeds of %d generators are what the generators write" % (count, len([g for g in GENERATORS if not only or g[0] in only])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
