# The C side stores the pool offset in 16 bits and the name length and the
# code point count in 8 each. Asserted here rather than assumed, so that a
# future entities.json that outgrows them fails the generator instead of
# producing a table that wraps.
MAX_POOL = 0xFFFF
MAX_LEN = 0xFF


def load(path):
    with open(path, encoding="utf-8") as handle:
        raw = json.load(handle)
    entries = []
    for key, value in raw.items():
        if not key.startswith("&"):
            raise SystemExit("entity key without a leading '&': %r" % key)
        name = key[1:]
        cps = value["codepoints"]
        if not 1 <= len(cps) <= 2:
            raise SystemExit("%s: %d code points; the C side holds 1 or 2"
                             % (key, len(cps)))
        for cp in cps:
            if not 0 <= cp <= 0x10FFFF or 0xD800 <= cp <= 0xDFFF:
                raise SystemExit("%s: U+%X is not a scalar value" % (key, cp))
        # The file also carries the expansion as a string; it must agree with
        # the code points, or one of the two is not what the spec means.
        if "".join(chr(c) for c in cps) != value["characters"]:
            raise SystemExit("%s: characters and codepoints disagree" % key)
        if not name.isascii() or not name:
            raise SystemExit("%s: name is not non-empty ASCII" % key)
        entries.append((name.encode("ascii"), tuple(cps)))
    entries.sort(key=lambda e: e[0])
    for a, b in zip(entries, entries[1:]):
        if a[0] == b[0]:
            raise SystemExit("duplicate name %r" % a[0])
    return entries


def emit(entries, source_sha):
    pool = bytearray()
    rows = []
    for name, cps in entries:
        off = len(pool)
        if len(name) > MAX_LEN:
            raise SystemExit("name %r longer than %d" % (name, MAX_LEN))
        pool += name
        rows.append((off, len(name), cps))
    if len(pool) > MAX_POOL:
        raise SystemExit("string pool is %d bytes; the offset is 16 bits"
                         % len(pool))
    longest = max(len(n) for n, _ in entries)
    shortest = min(len(n) for n, _ in entries)

    out = [LICENSE, """
/**
 * @file
 *
 * GENERATED by tools/html/gen_charrefs.py from entities.json
 * (sha256 %s).
 * Do not edit.
 *
 * Regenerate with:  tools/html/gen_charrefs.py
 * Verify with:      make check-html-tables
 */

#include "../charref_internal.h"

const size_t gtext_html_charref_count = %d;
const size_t gtext_html_charref_shortest = %d;
const size_t gtext_html_charref_longest = %d;

""" % (source_sha, len(entries), shortest, longest)]

    # The pool, as a brace-enclosed list of character constants rather than a
    # string literal. The obvious spelling is one adjacent-literal string, and
    # it does not compile here: the pool is 16 KB, ISO C only promises 4095
    # bytes in a string literal, and the library builds -pedantic with
    # -Woverlength-strings. The list also has no terminator, so no entry can
    # run off the end into one.
    out.append("const char gtext_html_charref_names[%d] = {\n" % len(pool))
    lines = []
    line = ""
    for byte in pool:
        piece = "'%s'," % chr(byte)
        if line and len(line) + 1 + len(piece) > 76:
            lines.append(line)
            line = ""
        line = line + " " + piece if line else piece
    lines.append(line)
    out.append("\n".join("  " + l for l in lines))
    out.append("\n};\n\n")

    out.append("const GTEXT_HTML_CharRef gtext_html_charref_table[%d] = {\n"
               % len(entries))
    for off, ln, cps in rows:
        second = cps[1] if len(cps) == 2 else 0
        out.append("  {%d, %d, %d, 0x%X, 0x%X},\n" % (off, ln, len(cps),
                                                     cps[0], second))
    out.append("};\n")
    return "".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--entities", default=os.path.join(
        ROOT, "third_party", "html", "entities.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "html", "tables"))
    args = ap.parse_args(argv)

    with open(args.entities, "rb") as handle:
        sha = hashlib.sha256(handle.read()).hexdigest()
    with open(os.path.join(HERE, "ENTITIES_SHA256"), encoding="ascii") as handle:
        pinned = handle.read().strip()
    if sha != pinned:
        raise SystemExit("entities.json is %s, pinned %s; run tools/html/"
                         "fetch.sh" % (sha, pinned))

    text = emit(load(args.entities), sha)
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "charref_table.c"), "w",
              encoding="ascii", newline="\n") as handle:
        handle.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
