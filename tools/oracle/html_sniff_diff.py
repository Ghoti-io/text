#!/usr/bin/env python3
"""The HTML encoding sniffer against html5lib's.

    html_sniff_diff.py <ours-runner> [--count N] [--seed S] [--write-list] [--plant NAME]

Documents generated by html_sniff_gen.py (byte order marks of five kinds, XML declarations, `<meta>` in every spelling, attribute
orders, quotes, white space, comments before the meta, labels from the Encoding Standard's table and names it does not know, the
edge of the 1024 bytes) are put through this library (html_sniff_ours.c) and through html5lib's input stream (containers/html/sniff.py,
`useChardet` off), each under a transport label that is certain, tentative or absent, a default or none, and with the `<meta>` ignored
or not. What is checked, each with its own heading when it fails (exit 3):

* **The label tables.** Every label webencodings knows, in four spellings, names the same encoding in both.
* **The model.** html_sniff_model.py is a second reading of the standard's algorithm, written from its text. With none of its switches
  on it must answer as this library does, on every document. (One reader is not a check on itself; two are.)
* **The departures.** Where html5lib answers otherwise, the smallest set of switches (each one a place where html5lib reads the algorithm
  differently: html5lib's own code is the evidence, and each has a witness) with which the model answers as html5lib did explains it.
  A disagreement no set explains fails the run. The list, html_sniff_divergences.txt, has a line per switch with the number of documents
  it takes part in, the rule of the standard it departs from, a witness (a document on which the two differ, explained by that switch and
  nothing else) and a control (the same document without the feature, on which they agree). A switch that no longer occurs, a count that has
  changed, a witness that does not show, and a switch with no line fail the run. (A count is the signature: a different reading of the same
  documents is a different count.)
* **The whole and the pieces.** The parser fed a byte at a time, and fed in two cuts, ends with the whole parser's encoding, confidence,
  byte order mark length and flags; and a restart happens only when the first reading was tentative, ends on a different encoding, and
  leaves the confidence certain.

Copyright 2026 by Corey Pennycuff
"""

import collections
import itertools
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import html_ref  # noqa: E402
import html_sniff_gen  # noqa: E402
import html_sniff_model  # noqa: E402
import oracle_env  # noqa: E402

SNIFF_PY = os.path.join(HERE, "containers", "html", "sniff.py")
VENV_PYTHON = "/opt/html-oracle/venv/bin/python3"
LIST = os.path.join(HERE, "html_sniff_divergences.txt")
DEFAULT_COUNT, DEFAULT_SEED = 6000, 1
RUNNER_SECONDS = 120
EXIT_FAIL = 3


def hexs(b):
    # "-" is no label, "=" the empty label (an empty token would not survive the runner's split)
    return "-" if b is None else ("=" if b == b"" else b.hex())


def ours_request(mode, doc, transport, certain, default, ignore):
    return "%s %s %s %s %d x%s" % (mode, hexs(transport), "c" if certain else "t", hexs(default), 1 if ignore else 0, doc.hex())


def run_ours(runner, requests):
    payload = ("\n".join(requests) + "\n").encode("ascii")
    try:
        done = subprocess.run([runner], input=payload, capture_output=True, timeout=RUNNER_SECONDS)
    except subprocess.TimeoutExpired:
        print("FAIL: This library's runner did not answer in %d seconds (a loop that does not end)" % RUNNER_SECONDS)
        sys.exit(EXIT_FAIL)
    if done.returncode != 0:
        print("FAIL: This library's runner exited %d:\n%s" % (done.returncode, done.stderr.decode("utf-8", "replace")[-2000:]))
        sys.exit(EXIT_FAIL)
    lines = done.stdout.decode("utf-8", "replace").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if len(lines) != len(requests):
        raise SystemExit("sent %d requests to this library's runner, got %d answers" % (len(requests), len(lines)))
    return lines


def run_theirs(requests, chunk=20000):
    html_ref.check_image()
    cmd = oracle_env.command("html", [VENV_PYTHON, SNIFF_PY])
    out = []
    for lo in range(0, len(requests), chunk):
        part = requests[lo:lo + chunk]
        payload = ("\n".join(json.dumps(r) for r in part) + "\n").encode("ascii")
        done = subprocess.run(cmd, input=payload, capture_output=True)
        if done.returncode != 0:
            raise SystemExit("html5lib's sniffer exited %d:\n%s" % (
                done.returncode, oracle_env.reference_stderr(done.stderr.decode("utf-8", "replace"))[-2000:]))
        lines = [l for l in done.stdout.decode("utf-8").split("\n") if l]
        if len(lines) != len(part):
            raise SystemExit("sent %d requests to html5lib, got %d answers" % (len(part), len(lines)))
        out.extend(json.loads(l) for l in lines)
    return out


def label_text(b):
    return None if b is None else b.decode("latin-1")


def theirs_request(mode, doc, transport, certain, default, ignore):
    return {"hex": doc.hex(), "transport": label_text(transport) if certain else None, "likely": None if certain else label_text(transport),
            "default": label_text(default) if default is not None else "utf-8", "ignore_meta": ignore, "mode": mode}


def parse_ours(line):
    f = line.split(" ")
    if f[0] == "error":
        return {"error": line}
    return {"enc": f[0].lower(), "source": int(f[1]), "conf": int(f[2]), "bom": int(f[3]), "reparsed": f[4] == "1", "ignored": f[5]}


class Process:
    """A question-and-answer child: one line in, one line out (the label tables are asked about while the models run)."""

    def __init__(self, cmd):
        self.p = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)

    def ask(self, line):
        self.p.stdin.write(line.encode("ascii") + b"\n")
        self.p.stdin.flush()
        got = self.p.stdout.readline()
        if not got:
            raise SystemExit("a label-table process went away")
        return got.decode("utf-8", "replace").rstrip("\n")

    def close(self):
        self.p.stdin.close()
        self.p.wait()


class LabelTables:
    """Which encoding a label names, in this library and in html5lib (webencodings), asked of each on demand and remembered."""

    def __init__(self, runner):
        html_ref.check_image()
        self.ours_p = Process([runner])
        self.theirs_p = Process(oracle_env.command("html", [VENV_PYTHON, SNIFF_PY]))
        self.ours_c, self.theirs_c = {}, {}

    def ours(self, label):
        if b"\x00" in label:  # (this library's labels are C strings: a NUL cannot be asked about, and no label has one)
            return None
        if label not in self.ours_c:
            r = parse_ours(self.ours_p.ask(ours_request("sniff", b"", label, True, None, True)))
            self.ours_c[label] = None if "error" in r or r["ignored"][0] == "1" else r["enc"]
        return self.ours_c[label]

    def theirs(self, label):
        if b"\x00" in label:
            return None
        if label not in self.theirs_c:
            r = json.loads(self.theirs_p.ask(json.dumps(theirs_request("sniff", b"", label, True, None, True))))
            self.theirs_c[label] = r["enc"] if r.get("conf") == "certain" else None
        return self.theirs_c[label]

    def close(self):
        self.ours_p.close()
        self.theirs_p.close()


MAX_SET = 5
CERTAIN = 0  # GTEXT_HTML_CERTAIN
FIELDS = ("name", "count", "explained_by", "w_default", "w_hex", "c_default", "c_hex", "rule")


def explain(item, want, tables):
    """(the smallest set of html5lib's departures (html_sniff_model.QUIRKS) with which the model answers as html5lib did, the number
    of sets of that size that do), or (None, 0)."""
    doc, transport, certain, default, ignore = item
    for size in range(MAX_SET + 1):
        found = []
        for chosen in itertools.combinations(html_sniff_model.QUIRKS, size):
            if html_sniff_model.sniff(doc, transport, certain, default, ignore, set(chosen), tables.ours) == want:
                found.append(chosen)
        if found:
            return found[0], len(found)
    return None, 0


def read_list(path):
    entries = {}
    with open(path) as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            cols = line.rstrip("\n").split("\t")
            if len(cols) != len(FIELDS):
                raise SystemExit("%s: a line has %d columns, not %d: %r" % (path, len(cols), len(FIELDS), line[:80]))
            e = dict(zip(FIELDS, cols))
            e["count"] = int(e["count"]) if e["count"] not in ("hunt", "COUNT") else None
            entries[e["name"]] = e
    return entries


def unhex_label(h):
    return None if h == "-" else bytes.fromhex(h)


def heading(out, text):
    out.append(text)


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--") and not a.isdigit() and not a.startswith("plant:")]
    count = int(os.environ.get("HTML_SNIFF_ORACLE_COUNT") or DEFAULT_COUNT)
    seed = int(os.environ.get("HTML_SNIFF_ORACLE_SEED") or DEFAULT_SEED)
    plant = None
    for i, a in enumerate(argv):
        if a == "--count":
            count = int(argv[i + 1])
        if a == "--seed":
            seed = int(argv[i + 1])
        if a == "--plant":
            plant = argv[i + 1]
    runner = args[0]
    if plant in ("ours-wrong", "incremental-wrong", "theirs-wrong", "label-wrong", "no-list", "stale-entry", "change-count", "witness", "control"):
        count, seed = DEFAULT_COUNT, DEFAULT_SEED  # (the controls are about the population the list describes)
    default_pop = (count, seed) == (DEFAULT_COUNT, DEFAULT_SEED)
    failures = []
    entries = {} if plant == "no-list" else read_list(LIST)
    if plant == "stale-entry":
        entries["gone"] = dict(entries[next(iter(entries))], name="gone", explained_by="gone")
    if plant == "change-count":
        first = next(iter(entries))
        entries[first] = dict(entries[first], count=entries[first]["count"] + 1)

    tables = LabelTables(runner)

    # ---- the label tables
    every = json.loads(tables.theirs_p.ask(json.dumps({"labels": True})))
    spelled = 0
    differ = []
    for L in every + [x for x in html_sniff_gen.LABELS + [x for x in html_sniff_gen.INVALID]]:
        base = L if isinstance(L, str) else L
        for v in (base, base.upper(), " " + base + "\t", base.title()):
            b = v.encode("latin-1", "replace")
            o, t = tables.ours(b), tables.theirs(b)
            if plant == "label-wrong" and spelled == 0:
                o = "utf-7"
            spelled += 1
            if o != t:
                differ.append((v, o, t))
    print("labels: %d spelled (%d webencodings labels, four spellings each, and the generator's); differing: %d" % (spelled, len(every), len(differ)))
    if differ:
        heading(failures, "Label tables differ")
        for v, o, t in differ[:10]:
            print("  label %r: this library %s, html5lib %s" % (v, o, t))

    # ---- the population
    pop = html_sniff_gen.population(count, seed)
    ours_reqs, theirs_reqs, keys = [], [], []
    for n, (doc, transport, certain, default, ignore, tags) in enumerate(pop):
        for mode in ("sniff", "parse", "bytes", "split"):
            ours_reqs.append(ours_request(mode, doc, transport, certain, default, ignore))
            keys.append((n, mode))
        theirs_reqs.append(theirs_request("sniff", doc, transport, certain, default, ignore))
    ours_all = [parse_ours(l) for l in run_ours(runner, ours_reqs)]
    theirs = run_theirs(theirs_reqs)
    ours = {}
    for (n, mode), o in zip(keys, ours_all):
        ours[(n, mode)] = o
    if plant == "ours-wrong":
        ours[(0, "sniff")] = dict(ours[(0, "sniff")], enc="utf-7")
    if plant == "incremental-wrong":
        ours[(0, "bytes")] = dict(ours[(0, "bytes")], enc="utf-7")
    if plant == "theirs-wrong":
        theirs[0] = {"enc": "utf-7", "conf": "tentative"}

    bad_model, parts, restarts = [], [], []
    participation, unexplained, ambiguous, plain, explained_docs = collections.Counter(), [], 0, 0, 0
    witness_doc = {}
    for n, (doc, transport, certain, default, ignore, tags) in enumerate(pop):
        o = ours[(n, "sniff")]
        t = theirs[n]
        item = (doc, transport, certain, default, ignore)
        m = html_sniff_model.sniff(doc, transport, certain, default, ignore, set(), tables.ours)
        if "error" in o or o["enc"] != m:
            bad_model.append((n, o, m))
        if "error" in t:
            unexplained.append((n, o, t))
        elif "error" in o or o["enc"] != t["enc"]:
            chosen, ties = explain(item, t["enc"], tables)
            if chosen is None:
                unexplained.append((n, o, t))
            else:
                if ties > 1:
                    ambiguous += 1
                explained_docs += 1
                for q in chosen:
                    participation[q] += 1
                    witness_doc.setdefault(q, n)
        else:
            plain += 1
        whole = ours[(n, "parse")]
        for mode in ("bytes", "split"):
            other = ours[(n, mode)]
            keep = lambda r: {k: r.get(k) for k in ("enc", "source", "conf", "bom", "reparsed", "ignored", "error")}
            if keep(other) != keep(whole):
                parts.append((n, mode, other, whole))
        if "error" not in whole and "error" not in o:
            first_certain = o["conf"] == CERTAIN
            moved = whole["enc"] != o["enc"]
            if whole["reparsed"] != moved or (moved and whole["conf"] != CERTAIN) \
                    or (first_certain and (moved or whole["reparsed"] or whole["conf"] != CERTAIN)):
                restarts.append((n, o, whole))
    print("documents: %d (seed %d); agreeing with html5lib: %d; departures of html5lib's explained: %d documents in %d switches (%d with more than one smallest set); "
          "unexplained: %d" % (len(pop), seed, plain, explained_docs, len(participation), ambiguous, len(unexplained)))
    print("model differs from this library: %d; incremental differs from whole: %d; restart invariants broken: %d" % (
        len(bad_model), len(parts), len(restarts)))
    if bad_model:
        heading(failures, "The model and this library disagree")
        for n, o, m in bad_model[:10]:
            print("  doc=%r transport=%r certain=%s default=%r ignore=%s\n     library=%s model=%s" % (
                pop[n][0][:300], pop[n][1], pop[n][2], pop[n][3], pop[n][4], o.get("enc", o), m))
    if unexplained:
        heading(failures, "Divergences that no departure of html5lib's explains")
        for n, o, t in unexplained[:10]:
            print("  doc=%r transport=%r certain=%s default=%r ignore=%s\n     library=%s html5lib=%s" % (
                pop[n][0][:300], pop[n][1], pop[n][2], pop[n][3], pop[n][4], o.get("enc", o), t))
    if parts:
        heading(failures, "The incremental parser's answer differs from the whole parser's")
        for n, mode, other, whole in parts[:10]:
            print("  doc=%r mode=%s\n     %s\n     whole %s" % (pop[n][0][:200], mode, other, whole))
    if restarts:
        heading(failures, "The restart is not what the confidence says")
        for n, o, whole in restarts[:10]:
            print("  doc=%r\n     first %s\n     final %s" % (pop[n][0][:200], o, whole))

    # ---- the list
    if "--write-list" in argv:
        for q in html_sniff_model.QUIRKS:
            print("LIST %s\t%d" % (q, participation.get(q, 0)))
    if default_pop:
        unlisted = sorted(set(participation) - set(entries))
        if unlisted:
            heading(failures, "Departures with no entry")
            for q in unlisted:
                print("  %s (%d documents)" % (q, participation[q]))
        gone = sorted(set(entries) - set(participation))
        if gone:
            heading(failures, "Listed departures that are gone")
            for q in gone:
                print("  %s" % q)
        changed = [(q, entries[q]["count"], participation[q]) for q in sorted(set(entries) & set(participation))
                   if entries[q]["count"] is not None and entries[q]["count"] != participation[q]]
        if changed:
            heading(failures, "Listed departures whose count has changed")
            for q, was, now in changed:
                print("  %s: listed %d, now %d" % (q, was, now))
    else:
        unknown = sorted(set(participation) - set(html_sniff_model.QUIRKS))
        if unknown:
            heading(failures, "Departures with no entry")

    # ---- the witnesses
    broken = []
    shown = 0
    for name, e in entries.items():
        if name not in html_sniff_model.QUIRKS:
            continue
        w_def, c_def = unhex_label(e["w_default"]), unhex_label(e["c_default"])
        w_doc, c_doc = bytes.fromhex(e["w_hex"]), bytes.fromhex(e["c_hex"])
        if plant == "witness" and shown == 0:
            w_doc = c_doc
        if plant == "control" and shown == 0:
            c_doc = w_doc
        shown += 1
        pair = []
        for doc, df in ((w_doc, w_def), (c_doc, c_def)):
            o = parse_ours(run_ours(runner, [ours_request("sniff", doc, None, True, df, False)])[0])
            t = run_theirs([theirs_request("sniff", doc, None, True, df, False)])[0]
            pair.append((doc, df, o, t))
        (wd, wdf, wo, wt), (cd, cdf, co, ct) = pair
        want = tuple(e["explained_by"].split("+"))
        got, _ = explain((wd, None, True, wdf, False), wt["enc"], tables)
        if wo["enc"] == wt["enc"]:
            broken.append("%s: the witness no longer shows it (both answer %s)" % (name, wo["enc"]))
        elif got != want:
            broken.append("%s: the witness is explained by %s, not %s" % (name, "+".join(got or ("nothing",)), "+".join(want)))
        if co["enc"] != ct["enc"]:
            broken.append("%s: the control does not agree (library %s, html5lib %s)" % (name, co["enc"], ct["enc"]))
    if broken:
        heading(failures, "A witness does not hold")
        for b in broken:
            print("  " + b)
    print("witnesses: %d, each showing its switch and agreeing with its control" % (len(entries) - len(broken)))

    tables.close()
    if failures:
        print()
        for f in failures:
            print("FAIL: " + f)
        return EXIT_FAIL
    print("html sniff differential: clean")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
